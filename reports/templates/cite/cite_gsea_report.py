def _section_pathway_table(
    results: dict[str, pd.DataFrame],
    summary_df: pd.DataFrame,
) -> str:
    """Top 3 pathways per cell type in a compact summary table + artifact flags."""
    gsea_flags_html = _check_gsea_flags(results, summary_df)

    if not results or summary_df.empty:
        # Try to build summary from raw results
        rows_html = "<p>No significant pathways found.</p>"
    else:
        # Detect column names
        _P_COL = next(
            (c for c in ["Adjusted P-value", "Adjusted P-Value", "FDR q-val"]
             if c in summary_df.columns), None
        )
        _T_COL = next(
            (c for c in ["Term", "term", "pathway"]
             if c in summary_df.columns), None
        )
        _GS_COL = next(
            (c for c in ["Gene_set", "Gene Set"]
             if c in summary_df.columns), None
        )

        if _T_COL is None or _P_COL is None:
            rows_html = "<p>Summary table columns not in expected format.</p>"
        else:
            trows = ""
            for _, row in summary_df.iterrows():
                term = str(row[_T_COL])
                term_short = term[:80] + "…" if len(term) > 80 else term
                pval = float(row[_P_COL]) if _P_COL else 1.0
                gs_badge = _db_tag(str(row[_GS_COL])) if _GS_COL else ""
                group = row.get("Group", row.get("group", ""))
                trows += (
                    f"<tr>"
                    f"<td>{group}</td>"
                    f"<td>{gs_badge} {term_short}</td>"
                    f"<td>{pval:.2e}</td>"
                    f"</tr>"
                )
            rows_html = f"""
            <table>
              <thead>
                <tr>
                  <th>Cell type</th>
                  <th>Top pathway</th>
                  <th>adj p-value</th>
                </tr>
              </thead>
              <tbody>{trows}</tbody>
            </table>"""

    return f"""
    <section>
      <h2>Top Pathways per Cell Type</h2>
      <p>
        Top 3 enriched pathways per ADT-defined cell type across all queried
        gene set libraries. Full results are stored in
        <code>uns["omicsage_cite_gsea"]</code>.
      </p>
      {gsea_flags_html}
      {rows_html}
    </section>"""


