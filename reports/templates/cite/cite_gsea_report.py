def _plot_top_pathways_bar(
    results: dict[str, pd.DataFrame],
    n_top: int = 10,
) -> str:
    """
    Horizontal bar chart: top n_top pathways per cell type, coloured by
    -log10(adjusted p-value). One panel per cell type.
    """
    # Determine the adjusted p-value column name (varies by gseapy version)
    _P_COL = None
    for candidate in ["Adjusted P-value", "Adjusted P-Value", "FDR q-val", "adj_pval"]:
        for df in results.values():
            if not df.empty and candidate in df.columns:
                _P_COL = candidate
                break
        if _P_COL:
            break

    # Term column
    _T_COL = None
    for candidate in ["Term", "term", "pathway", "Description"]:
        for df in results.values():
            if not df.empty and candidate in df.columns:
                _T_COL = candidate
                break
        if _T_COL:
            break

    cell_types = [ct for ct, df in results.items() if not df.empty]
    if not cell_types or _P_COL is None or _T_COL is None:
        fig, ax = plt.subplots(figsize=(5, 2))
        ax.text(0.5, 0.5, "No significant pathways to display.",
                ha="center", va="center", transform=ax.transAxes,
                fontsize=10, color="#888")
        ax.axis("off")
        return _fig_to_b64(fig)

    n_cols = min(2, len(cell_types))
    n_rows = (len(cell_types) + n_cols - 1) // n_cols
    fig, axes = plt.subplots(n_rows, n_cols,
                              figsize=(n_cols * 6.5, n_rows * 4))
    axes = np.array(axes).flatten()

    for i, ct in enumerate(cell_types):
        ax = axes[i]
        df = results[ct].copy()

        if df.empty or _P_COL not in df.columns:
            ax.axis("off")
            continue

        df = df[df[_P_COL] < 1.0].nsmallest(n_top, _P_COL)
        if df.empty:
            ax.axis("off")
            continue

        # Shorten long pathway names
        terms = df[_T_COL].astype(str).apply(
            lambda t: t[:55] + "…" if len(t) > 55 else t
        ).tolist()
        neg_log_p = -np.log10(df[_P_COL].clip(lower=1e-300).values)

        # Colour by database if Gene_set column present
        if "Gene_set" in df.columns:
            gene_sets = df["Gene_set"].astype(str).tolist()
            palette = {
                "GO": "#4C78A8",
                "KEGG": "#54a868",
                "Reactome": "#e07b3a",
            }
            bar_colors = []
            for gs in gene_sets:
                if "GO" in gs or "Biological" in gs:
                    bar_colors.append(palette["GO"])
                elif "KEGG" in gs:
                    bar_colors.append(palette["KEGG"])
                elif "Reactome" in gs:
                    bar_colors.append(palette["Reactome"])
                else:
                    bar_colors.append("#9467bd")
        else:
            bar_colors = ["#4C78A8"] * len(terms)

        ax.barh(terms[::-1], neg_log_p[::-1],
                color=bar_colors[::-1], alpha=0.85, height=0.65)
        ax.axvline(
            -np.log10(0.05), color="#c0392b",
            linewidth=1, linestyle="--", alpha=0.7,
            label="adj p = 0.05",
        )
        ax.set_title(ct, fontsize=9, fontweight="bold")
        ax.set_xlabel("−log₁₀(adj p-value)", fontsize=8)
        ax.tick_params(axis="y", labelsize=6.5)
        ax.tick_params(axis="x", labelsize=7)
        ax.spines[["top", "right"]].set_visible(False)
        if i == 0:
            ax.legend(fontsize=7, frameon=False)

    for j in range(len(cell_types), len(axes)):
        axes[j].axis("off")

    fig.suptitle(
        f"Top {n_top} Pathways per Cell Type  (−log₁₀ adjusted p-value)",
        fontsize=12, fontweight="bold", y=1.01,
    )
    fig.tight_layout()
    return _fig_to_b64(fig)


def _plot_pathway_heatmap(
    results: dict[str, pd.DataFrame],
    n_top: int = 5,
) -> str:
    """
    Heatmap: rows = top pathways (union across cell types),
    columns = cell types, values = -log10(adj p-value).
    Shows the shared pathway landscape across all populations.
    """
    _P_COL = None
    _T_COL = None
    for candidate_p in ["Adjusted P-value", "Adjusted P-Value", "FDR q-val"]:
        for candidate_t in ["Term", "term", "pathway"]:
            for df in results.values():
                if (not df.empty
                        and candidate_p in df.columns
                        and candidate_t in df.columns):
                    _P_COL = candidate_p
                    _T_COL = candidate_t
                    break
            if _P_COL:
                break
        if _P_COL:
            break

    if _P_COL is None or _T_COL is None:
        fig, ax = plt.subplots(figsize=(4, 2))
        ax.text(0.5, 0.5, "Pathway heatmap: required columns not found.",
                ha="center", va="center", transform=ax.transAxes,
                fontsize=9, color="#888")
        ax.axis("off")
        return _fig_to_b64(fig)

    # Collect top n_top pathways per cell type
    top_terms: list[str] = []
    for ct, df in results.items():
        if df.empty:
            continue
        terms = df.nsmallest(n_top, _P_COL)[_T_COL].tolist()
        top_terms.extend(terms)

    # Deduplicate preserving order
    seen: set[str] = set()
    unique_terms: list[str] = []
    for t in top_terms:
        if t not in seen:
            seen.add(t)
            unique_terms.append(t)

    if not unique_terms:
        fig, ax = plt.subplots(figsize=(4, 2))
        ax.text(0.5, 0.5, "No pathways to show in heatmap.",
                ha="center", va="center", transform=ax.transAxes,
                fontsize=9, color="#888")
        ax.axis("off")
        return _fig_to_b64(fig)

    cell_types = list(results.keys())

    # Build matrix
    matrix = np.zeros((len(unique_terms), len(cell_types)))
    for j, ct in enumerate(cell_types):
        df = results[ct]
        if df.empty or _T_COL not in df.columns:
            continue
        term_to_p = dict(zip(df[_T_COL], df[_P_COL]))
        for i, term in enumerate(unique_terms):
            p = term_to_p.get(term, 1.0)
            matrix[i, j] = -np.log10(max(p, 1e-300))

    # Shorten labels
    ylabels = [t[:60] + "…" if len(t) > 60 else t for t in unique_terms]

    fig_h = max(5, len(unique_terms) * 0.35)
    fig_w = max(6, len(cell_types) * 1.2)
    fig, ax = plt.subplots(figsize=(fig_w, fig_h))

    im = ax.imshow(matrix, aspect="auto", cmap="YlOrRd",
                   vmin=0, vmax=max(matrix.max(), 1))
    plt.colorbar(im, ax=ax, fraction=0.03, pad=0.02,
                 label="−log₁₀(adj p-value)")

    ax.set_xticks(range(len(cell_types)))
    ax.set_xticklabels(cell_types, rotation=30, ha="right", fontsize=9)
    ax.set_yticks(range(len(unique_terms)))
    ax.set_yticklabels(ylabels, fontsize=7)
    ax.set_title(
        f"Pathway Enrichment Heatmap\n"
        f"(top {n_top} pathways per cell type, union shown)",
        fontsize=11, fontweight="bold",
    )
    fig.tight_layout()
    return _fig_to_b64(fig)


