def _section_run_summary(
    provenance: dict,
    dataset_name: str,
    timestamp: str,
) -> str:
    n_tested  = provenance.get("n_groups_tested", "?")
    n_skipped = provenance.get("n_groups_skipped", "?")
    gene_sets = provenance.get("gene_sets") or ["GO_Biological_Process_2023",
                                                 "KEGG_2021_Human",
                                                 "Reactome_2022"]
    direction  = provenance.get("direction", "up")
    organism   = provenance.get("organism", "human")
    note_str   = provenance.get("note", "")
    skipped    = provenance.get("groups_skipped", [])

    db_badges = " ".join(_db_tag(gs) for gs in gene_sets)

    skipped_html = ""
    if skipped:
        skip_items = "".join(
            f"<li><code>{g}</code> ({d})</li>" for g, d in skipped
        )
        skipped_html = (
            f"<p class='note'>Groups skipped (fewer than min_genes DEGs): "
            f"<ul>{skip_items}</ul></p>"
        )

    cards = "".join(
        f'<div class="stat-card"><div class="stat-value">{v}</div>'
        f'<div class="stat-label">{k}</div></div>'
        for k, v in [
            ("Groups tested",  n_tested),
            ("Groups skipped", n_skipped),
            ("Direction",      direction),
            ("Organism",       organism),
        ]
    )
    rows = "".join(
        f"<tr><td>{k}</td><td>{v}</td></tr>"
        for k, v in [
            ("Gene set libraries", db_badges),
            ("Min log2FC",         provenance.get("min_logfc", "?")),
            ("Max adj p-value",    provenance.get("max_pval_adj", "?")),
            ("Source DEG module",  provenance.get("source_deg_module", "cite_deg")),
        ]
    )
    return f"""
    <section>
      <h2>Run Summary</h2>
      <p class="timestamp">Dataset: <strong>{dataset_name}</strong>
         &middot; {timestamp}</p>
      <p style="color:#444;font-size:0.88rem;">{note_str}</p>
      {skipped_html}
      <div class="stat-grid">{cards}</div>
      <table>
        <thead><tr><th>Parameter</th><th>Value</th></tr></thead>
        <tbody>{rows}</tbody>
      </table>
    </section>"""


