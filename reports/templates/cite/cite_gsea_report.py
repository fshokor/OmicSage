def run_cite_gsea_report(
    gsea_dict: dict,
    report_path: str = "reports/cite_08_gsea_report.html",
    dataset_name: str = "dataset",
) -> str:
    """
    Generate the CITE-seq GSEA HTML report.

    Parameters
    ----------
    gsea_dict : dict
        Dict returned by cite_gsea(). Keys: results, summary_df,
        provenance, skipped.
    report_path : str
        Where to write the HTML file.
    dataset_name : str
        Dataset display name for the report header.

    Returns
    -------
    str
        Absolute path to the written HTML file.
    """
    out = Path(report_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M")

    results    = gsea_dict.get("results", {})
    summary_df = gsea_dict.get("summary_df", pd.DataFrame())
