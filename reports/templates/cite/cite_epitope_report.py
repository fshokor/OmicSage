def _section_run_summary(
    provenance: dict,
    dataset_name: str,
    timestamp: str,
) -> str:
    n_panels   = provenance.get("n_panels", 0)
    panel_names= ", ".join(provenance.get("panel_names", [])) or "none"
    preset     = provenance.get("preset") or "custom"
    has_corr   = provenance.get("has_corr_results", False)
    has_dpe    = provenance.get("has_dpe_results", False)
    groupby    = provenance.get("groupby", "?")

    cards = "".join(
        f'<div class="stat-card"><div class="stat-value">{v}</div>'
        f'<div class="stat-label">{k}</div></div>'
        for k, v in [
            ("Panels",          n_panels),
            ("Panel source",    preset),
            ("Corr results",    "✓" if has_corr else "✗"),
            ("DPE results",     "✓" if has_dpe  else "✗"),
        ]
    )
    missing = []
    if not has_corr:
        missing.append("cite_09 (protein-RNA correlation) — parallel violin plots skipped")
    if not has_dpe:
        missing.append("cite_07 (DEG/DPE) — cross-modal marker table skipped")
    missing_html = ""
    if missing:
        items = "".join(f"<li>{m}</li>" for m in missing)
        missing_html = (
            f"<p class='note'>Optional upstream results not provided — "
            f"some sub-analyses were skipped:<ul>{items}</ul></p>"
        )

    rows = "".join(
        f"<tr><td>{k}</td><td><code>{v}</code></td></tr>"
        for k, v in [
            ("Groupby",    groupby),
            ("Panels",     panel_names),
        ]
    )
    return f"""
    <section>
      <h2>Run Summary</h2>
      <p class="timestamp">Dataset: <strong>{dataset_name}</strong>
         &middot; {timestamp}</p>
      {missing_html}
      <div class="stat-grid">{cards}</div>
      <table>
        <thead><tr><th>Parameter</th><th>Value</th></tr></thead>
        <tbody>{rows}</tbody>
      </table>
    </section>"""


def _section_epitope_scores(
    mdata,
    scores_df: pd.DataFrame,
    panel_used: dict,
    group_col: str,
) -> str:
    if not panel_used or scores_df.empty:
        return """
    <section>
      <h2>Epitope Abundance Scores</h2>
      <p class="note">No panels configured — set preset or epitope_panels
      in the config.</p>
    </section>"""

    print("  Rendering epitope score heatmap ...", flush=True)
    fig_heatmap = _plot_score_heatmap(mdata, scores_df, panel_used, group_col)

    # Per-panel violin plots — one per panel
    violin_html = ""
    for panel_name in list(panel_used.keys())[:6]:  # cap at 6 for report size
        print(f"  Rendering score violin: {panel_name} ...", flush=True)
        fig_v = _plot_score_violin(mdata, scores_df, panel_name, group_col)
        violin_html += f"""
        <div class="fig-wrap">
          <h3>{panel_name}</h3>
          <img src="data:image/png;base64,{fig_v}" alt="{panel_name} score">
        </div>"""

    return f"""
    <section>
      <h2>Epitope Abundance Scores</h2>
      <p>
        Mean CLR expression of lineage-defining proteins grouped into panels.
        Scores are written to <code>obs["epitope_score_*"]</code> and can be
        used as continuous lineage markers for downstream trajectory analysis.
        Higher score = stronger expression of that lineage's surface markers.
      </p>
      <h3>Panel Score Heatmap (mean per cell type)</h3>
      <div class="fig-grid">
        <div class="fig-wrap wide">
          <img src="data:image/png;base64,{fig_heatmap}" alt="Epitope score heatmap">
        </div>
      </div>
      <h3>Per-Panel Score Distribution</h3>
      <div class="fig-grid">{violin_html}</div>
    </section>"""


def _section_rna_protein_parallel(
    mdata,
    corr_results: Optional[pd.DataFrame],
    group_col: str,
    n_pairs: int = 6,
) -> str:
    if corr_results is None or corr_results.empty:
        return """
    <section>
      <h2>RNA-Protein Parallel Plots</h2>
      <p class="note">
        Requires cite_09 correlation results.
        Re-run with cite_09 checkpoint available to enable this section.
      </p>
    </section>"""

    # Select top n_pairs by highest POSITIVE r
    # (co-regulated pairs where protein and mRNA agree — most illustrative
    # for showing what the parallel plot is designed to show).
    # Negatively correlated pairs (anti-correlated) are shown separately below.
    df = corr_results.copy()
    pairs_pos = df[df["r"] > 0].nlargest(n_pairs, "r")[["protein", "gene", "r"]].values.tolist()
    # If fewer than n_pairs positive pairs exist, fill with least-negative
    if len(pairs_pos) < n_pairs:
        pairs_neg_fill = (
            df[df["r"] <= 0]
            .nlargest(n_pairs - len(pairs_pos), "r")
            [["protein", "gene", "r"]].values.tolist()
        )
        pairs = pairs_pos + pairs_neg_fill
    else:
        pairs = pairs_pos

    pair_html = ""
    for protein, gene, r in pairs:
        print(f"  Rendering RNA-protein parallel: {protein}/{gene} ...", flush=True)
        fig_b64 = _plot_rna_protein_parallel(
            mdata, str(protein), str(gene), float(r), group_col
        )
        r_str = f"r = {float(r):.3f}"
        pair_html += f"""
        <div class="fig-wrap wide" style="margin-bottom:20px;">
          <h3>{protein} / {gene} &nbsp;<span style="font-weight:400;color:#666;font-size:0.85rem;">Spearman {r_str}</span></h3>
          <img src="data:image/png;base64,{fig_b64}"
               alt="{protein} protein vs {gene} RNA">
        </div>"""

    return f"""
    <section>
      <h2>RNA-Protein Parallel Plots</h2>
      <div class="interp">
        Each pair shows the same protein measured two ways: surface protein
        abundance (CLR, left) and mRNA expression (log-normalised, right),
        both grouped by ADT-defined cell type.
        When the shapes match — the two modalities agree.
        When they diverge — post-transcriptional regulation, differential
        secretion, or surface trafficking is at work. These are biological
        findings, not noise.
      </div>
      <p>Showing top {n_pairs} positively correlated pairs from cite_09
      (pairs where protein and mRNA are co-regulated — shapes should match).
      These are the most informative for validating RNA-protein coupling.</p>
      <div class="fig-grid">{pair_html}</div>
    </section>"""


def _section_marker_table(marker_table: pd.DataFrame) -> str:
    if marker_table.empty:
        return """
    <section>
      <h2>Cross-Modal Marker Table</h2>
      <p class="note">
        Requires cite_07 DEG/DPE results.
        Re-run with cite_07 checkpoint available to enable this section.
      </p>
    </section>"""

    def _r_cell(r_val) -> str:
        try:
            r = float(r_val)
        except (TypeError, ValueError):
            return "<td>—</td>"
        if np.isnan(r):
            return "<td>—</td>"
        css = "r-high" if r >= 0.4 else ("r-neg" if r < 0 else "r-low")
        return f"<td class='{css}'>{r:.3f}</td>"

    trows = ""
    prev_ct = None
    for _, row in marker_table.iterrows():
        ct = row["cell_type"]
        ct_cell = (
            f"<td rowspan='1' style='font-weight:600'>{ct}</td>"
            if ct != prev_ct else "<td></td>"
        )
        prev_ct = ct
        trows += (
            f"<tr>"
            f"{ct_cell}"
            f"<td><strong>{row['protein']}</strong></td>"
            f"<td>{float(row['logfc']):.3f}</td>"
            f"<td>{float(row['pval_adj']):.2e}</td>"
            f"<td><code>{row['rna_gene']}</code></td>"
            f"{_r_cell(row['r'])}"
            f"</tr>"
        )

    return f"""
    <section>
      <h2>Cross-Modal Marker Table</h2>
      <p>
        Top ADT marker proteins per cell type (from DPE, cite_07), annotated
        with their RNA counterpart gene and Spearman correlation r (cite_09).
        Pairs with r &ge; 0.4 show strong RNA-protein coupling.
        Pairs with low r are post-transcriptionally regulated —
        the protein is a better cell-type marker than the mRNA.
      </p>
      <table>
        <thead>
          <tr>
            <th>Cell type</th>
            <th>Protein (ADT)</th>
            <th>log2FC</th>
            <th>adj p-value</th>
            <th>RNA gene</th>
            <th>Spearman r</th>
          </tr>
        </thead>
        <tbody>{trows}</tbody>
      </table>
    </section>"""


