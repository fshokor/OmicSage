def _plot_score_heatmap(
    mdata,
    scores_df: pd.DataFrame,
    panel_used: dict,
    group_col: str,
) -> str:
    """
    Heatmap: rows = cell types, columns = epitope panels,
    values = mean epitope score per cell type.
    """
    if scores_df.empty or not panel_used:
        fig, ax = plt.subplots(figsize=(5, 2))
        ax.text(0.5, 0.5, "No epitope scores to display.",
                ha="center", va="center", transform=ax.transAxes,
                fontsize=10, color="#888")
        ax.axis("off")
        return _fig_to_b64(fig)

    adt = mdata["adt"]
    if group_col not in adt.obs.columns:
        fig, ax = plt.subplots(figsize=(5, 2))
        ax.text(0.5, 0.5, f"Group column '{group_col}' not found.",
                ha="center", va="center", transform=ax.transAxes,
                fontsize=9, color="#888")
        ax.axis("off")
        return _fig_to_b64(fig)

    panel_names = [p for p in panel_used.keys() if p in scores_df.columns]
    if not panel_names:
        fig, ax = plt.subplots(figsize=(5, 2))
        ax.text(0.5, 0.5, "Panel score columns not found in scores_df.",
                ha="center", va="center", transform=ax.transAxes,
                fontsize=9, color="#888")
        ax.axis("off")
        return _fig_to_b64(fig)

    cell_types = sorted(adt.obs[group_col].astype(str).unique())
    scores_df = scores_df.copy()
    scores_df["cell_type"] = adt.obs[group_col].astype(str).values

    matrix = np.zeros((len(cell_types), len(panel_names)))
    for i, ct in enumerate(cell_types):
        subset = scores_df[scores_df["cell_type"] == ct]
        for j, panel in enumerate(panel_names):
            matrix[i, j] = subset[panel].mean() if not subset.empty else 0.0

    fig_h = max(4, len(cell_types) * 0.5)
    fig_w = max(6, len(panel_names) * 1.2)
    fig, ax = plt.subplots(figsize=(fig_w, fig_h))

    im = ax.imshow(matrix, aspect="auto", cmap="YlOrRd",
                   vmin=0, vmax=max(matrix.max(), 0.01))
    plt.colorbar(im, ax=ax, fraction=0.03, pad=0.02,
                 label="Mean CLR score")

    ax.set_xticks(range(len(panel_names)))
    ax.set_xticklabels(panel_names, rotation=30, ha="right", fontsize=9)
    ax.set_yticks(range(len(cell_types)))
    ax.set_yticklabels(cell_types, fontsize=9)
    ax.set_title(
        "Mean Epitope Score per Cell Type\n"
        "(CLR expression of panel proteins, averaged per cell then per group)",
        fontsize=11, fontweight="bold",
    )
    fig.tight_layout()
    return _fig_to_b64(fig)


def _plot_score_violin(
    mdata,
    scores_df: pd.DataFrame,
    panel_name: str,
    group_col: str,
) -> str:
    """
    Violin plot of one epitope panel score across all cell types.
    """
    if scores_df.empty or panel_name not in scores_df.columns:
        fig, ax = plt.subplots(figsize=(5, 2))
        ax.text(0.5, 0.5, f"No data for panel '{panel_name}'.",
                ha="center", va="center", transform=ax.transAxes,
                fontsize=9, color="#888")
        ax.axis("off")
        return _fig_to_b64(fig)

    adt = mdata["adt"]
    df = scores_df.copy()
    df["cell_type"] = adt.obs[group_col].astype(str).values

    cell_types = sorted(df["cell_type"].unique())
    data = [df[df["cell_type"] == ct][panel_name].values for ct in cell_types]
    data = [d for d in data if len(d) > 0]

    if not data:
        fig, ax = plt.subplots(figsize=(5, 2))
        ax.axis("off")
        return _fig_to_b64(fig)

    cmap = plt.get_cmap("tab10", len(cell_types))
    fig, ax = plt.subplots(figsize=(max(6, len(cell_types) * 0.9), 4))

    parts = ax.violinplot(data, positions=range(len(cell_types)),
                          showmedians=True, showextrema=False)
    for i, pc in enumerate(parts["bodies"]):
        pc.set_facecolor(cmap(i))
        pc.set_alpha(0.75)
    parts["cmedians"].set_color("#333")

    ax.set_xticks(range(len(cell_types)))
    ax.set_xticklabels(cell_types, rotation=30, ha="right", fontsize=8)
    ax.set_ylabel("Mean CLR score", fontsize=9)
    ax.set_title(f"{panel_name} Epitope Score", fontsize=10, fontweight="bold")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    return _fig_to_b64(fig)


def _plot_rna_protein_parallel(
    mdata,
    protein: str,
    gene: str,
    r: float,
    group_col: str,
    n_top_types: int = 8,
) -> str:
    """
    Side-by-side violin: CLR expression (left) vs log-RNA (right)
    for one protein-gene pair, per cell type.
    This is the core Seurat multimodal vignette figure.
    """
    adt = mdata["adt"]
    rna = mdata["rna"]

    # Get cell type labels
    if group_col not in adt.obs.columns:
        fig, ax = plt.subplots(figsize=(4, 2))
        ax.axis("off")
        return _fig_to_b64(fig)

    labels = adt.obs[group_col].astype(str).values

    # Limit to top n_top_types by cell count for readability
    from collections import Counter
    counts = Counter(labels)
    top_types = [ct for ct, _ in counts.most_common(n_top_types)]

    # Get protein CLR vector
    prot_vec = None
    if protein in adt.var_names:
        pidx = list(adt.var_names).index(protein)
        mat = adt.layers.get("adt_clr", adt.X)
        mat = mat.toarray() if hasattr(mat, "toarray") else np.asarray(mat)
        prot_vec = mat[:, pidx].ravel()

    # Get RNA log vector
    rna_vec = None
    if gene in rna.var_names:
        gidx = list(rna.var_names).index(gene)
        rmat = rna.layers.get("logcounts", rna.X)
        rmat = rmat.toarray() if hasattr(rmat, "toarray") else np.asarray(rmat)
        rna_vec = rmat[:, gidx].ravel()

    if prot_vec is None or rna_vec is None:
        fig, ax = plt.subplots(figsize=(4, 2))
        ax.text(0.5, 0.5,
                f"'{protein}' or '{gene}' not found.",
                ha="center", va="center", transform=ax.transAxes,
                fontsize=8, color="#888")
        ax.axis("off")
        return _fig_to_b64(fig)

    mask = np.isin(labels, top_types)
    labels_f  = labels[mask]
    prot_f    = prot_vec[mask]
    rna_f     = rna_vec[mask]

    cmap = plt.get_cmap("tab10", len(top_types))
    fig, (ax_p, ax_r) = plt.subplots(1, 2, figsize=(12, 4), sharey=False)

    for ax, values, ylabel, title in [
        (ax_p, prot_f, "CLR expression",  f"{protein} (protein)"),
        (ax_r, rna_f,  "log expression",  f"{gene} (RNA)"),
    ]:
        data = [values[labels_f == ct] for ct in top_types]
        data = [d for d in data if len(d) > 0]
        if not data:
            ax.axis("off")
            continue

        parts = ax.violinplot(data, positions=range(len(top_types)),
                               showmedians=True, showextrema=False)
        for i, pc in enumerate(parts["bodies"]):
            pc.set_facecolor(cmap(i))
            pc.set_alpha(0.75)
        parts["cmedians"].set_color("#333")

        ax.set_xticks(range(len(top_types)))
        ax.set_xticklabels(top_types, rotation=30, ha="right", fontsize=8)
        ax.set_ylabel(ylabel, fontsize=9)
        ax.set_title(title, fontsize=10, fontweight="bold")
        ax.spines[["top", "right"]].set_visible(False)

    r_str = f"r = {r:.3f}" if not np.isnan(r) else "r = n/a"
    fig.suptitle(
        f"{protein} protein  ⟷  {gene} RNA  ({r_str})",
        fontsize=11, fontweight="bold",
    )
    fig.tight_layout()
    return _fig_to_b64(fig)


