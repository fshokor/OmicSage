def run_cite_corr_report(
    corr_dict: dict,
    report_path: str = "reports/cite_09_corr_report.html",
    dataset_name: str = "dataset",
) -> str:
    """
    Generate the CITE-seq protein-RNA correlation HTML report.

    Parameters
    ----------
    corr_dict : dict
        Dict returned by cite_corr(). Keys: results, matched, unmatched,
        skipped, provenance.
    report_path : str
        Where to write the HTML file.
    dataset_name : str
        Dataset display name for the report header.

    Returns
    -------
    str
        Absolute path to the written HTML file.
    """
    out = Path(report_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M")

    results_df = corr_dict.get("results", pd.DataFrame())
    provenance = corr_dict.get("provenance", {})

    print(f"Building CITE correlation report for '{dataset_name}' ...", flush=True)

    sections = [
        _section_run_summary(provenance, dataset_name, timestamp),
        _section_figures(results_df),
        _section_results_tables(results_df),
    ]

    html = _render_page(sections, timestamp, dataset_name)
    out.write_text(html, encoding="utf-8")
    print(f"Report saved -> {out.resolve()}", flush=True)
    return str(out.resolve())
